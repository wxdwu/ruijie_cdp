"""
客户黑名单规则（非法/脏数据正则），以 Python 常量提供，无需写入数据库。

与 `customer_service._apply_customer_filters` 协同：命中任一黑名单规则且无联系人/互动
（保命条件）即剔除；不确定的数据默认保留。
"""

from typing import List

# 黑名单：明显非法/占位/脏数据规则（优先正则通用拼写，破碎特例硬编码）。
# 命中任一规则且无联系人/互动（保命条件）即剔除。不确定的数据默认保留。
VALID_BLACKLIST_PATTERNS: List[str] = [
    # 测试/占位/未知/无意义
    r"test|testing|测试|试用|未知|unknow|unknown|null|none|nil|待定|tbd|"
    r"xxx|x{3,}|占位|样例|示例|demo|temp|tmp",
    # 邮箱/@/URL
    r"@|https?://|www\.|\.com|\.cn|\.net|\.org|\.edu",
    # 6 位及以上纯数字（ID/手机号片段/错误拼接；短数字品牌如 360/58 已在白名单特例）
    r"^[0-9]{6,}$",
    # 不可见/脏字符/破碎括号（前导控制字符、全角空格、左引号、破折号、顿号、
    # 半括号+单字母等）。注意：本项不能用原始字符串，需 Python 转义
    # \u3000(全角空格)/\u201c(左双引号)/\"(双引号)。
    "[\t\r\n]|^\u3000|^\"|^\u201c|^—|、|（c$|（jns$",
    # 单字（长度<2，基本为脏数据）
    r"^.$",
]
